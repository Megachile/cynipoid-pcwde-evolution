#!/usr/bin/env python3
"""preprocess_domains.py — Trim proteins to PCWDE domain ± flanking sequence.

All proteins (cynipoid and outgroup) are trimmed to the predicted catalytic
domain boundaries ± FLANK amino acids. Proteins with multiple non-overlapping
domains (>30% HMM coverage each) are split into separate entries. Gene-model
fusions (single domain, >2x median length, domain <50% of protein) are excluded.

Inputs: --protein-dir (or PCWDE_PROTEIN_DIR) contains each family's .faa
and _domtbl.txt files in hmmsearch format. Overlap resolution defaults to
lowest independent domain E-value with inclusive coordinates. Use
--overlap-rule legacy-diagnostic only to compare historical preprocessing.
The manuscript build consumes fixed alignments and trees; it does not use
newly preprocessed sequences.

Outputs: --output-dir (default: build/proteins) receives the three trimmed
FASTAs and preprocess_report.tsv. The output directory must not exist and
must be separate from the inputs. All required inputs are checked first.

Usage: python3 -B scripts/analysis/preprocess_domains.py --protein-dir INPUTS --output-dir build/proteins
"""

import argparse, math, os, re, sys, csv, statistics
from pathlib import Path
from collections import defaultdict, OrderedDict

from fusion_filter import (
    FUSION_ALIGNED_COVERAGE_MAX,
    FUSION_LENGTH_MULTIPLIER,
    is_apparent_gene_prediction_fusion,
)

REPO = Path(__file__).resolve().parents[2]
PROTEIN_DIR = Path(os.environ.get("PCWDE_PROTEIN_DIR", Path(os.environ.get("PCWDE_DATA_ROOT", REPO / "figshare_data")) / "repository_inputs/analysis/domain_preparation"))

FAMILIES = ["GH5_2", "PL1_8", "PL4_4"]

# Family → target HMM name in domtbl
# Domtbl files generated by: hmmsearch --domtblout {family}_domtbl.txt pcwde_3subfam.hmm {family}.faa
FAMILY_HMM = {
    "GH5_2": "GH5_2.hmm",
    "PL1_8": "PL1_8.hmm",
    "PL4_4": "PL4_4.hmm",
}

FLANK = 50           # aa flanking on each side of domain
MIN_HMM_COV = 0.30   # minimum HMM coverage to count as a real domain copy
# Backward-compatible names for audited consumers. The decision itself lives
# only in fusion_filter.is_apparent_gene_prediction_fusion.
FUSION_LEN_MULT = FUSION_LENGTH_MULTIPLIER
FUSION_DOM_FRAC = FUSION_ALIGNED_COVERAGE_MAX
OUTGROUP_PFX = ("bacterium|", "nematode|", "oomycete|", "fungus|", "plant|",
                "protist|", "midge|", "bee|", "beetle|")


def read_faa(path):
    seqs = OrderedDict()
    current_id = None
    current_seq = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line.startswith(">"):
                if current_id is not None:
                    seqs[current_id] = "".join(current_seq)
                current_id = line.lstrip(">").split()[0]
                current_seq = []
            else:
                current_seq.append(line)
    if current_id is not None:
        seqs[current_id] = "".join(current_seq)
    return seqs


def parse_domtbl(path, target_hmm):
    """Parse hmmsearch domtblout, return dict: protein_name -> list of domain hits.

    hmmsearch domtblout format: columns are
    [0] target_name (protein), [2] tlen, [3] query_name (HMM), [5] qlen,
    [6] full_evalue, [12] i_evalue, [15] hmm_from, [16] hmm_to,
    [17] ali_from, [18] ali_to
    """
    hits = defaultdict(list)
    with open(path) as f:
        for line_number, line in enumerate(f, 1):
            if line.lstrip().startswith("#"):
                if re.search(r"#\s*Program:\s*hmmscan\b", line):
                    raise ValueError("expected hmmsearch, received hmmscan: " + str(path))
                continue
            if not line.strip():
                continue
            parts = line.split()
            if len(parts) < 22:
                raise ValueError(f"malformed hmmsearch row {path}:{line_number}")
            if parts[0] == target_hmm:
                raise ValueError("inverted HMM/protein orientation; expected hmmsearch")
            hmm_name = parts[3]  # hmmsearch: query=HMM, target=protein
            if hmm_name != target_hmm:
                continue
            protein = parts[0]
            hit = {
                "i_evalue": float(parts[12]),
                "ali_from": int(parts[17]),  # 1-based
                "ali_to": int(parts[18]),
                "hmm_from": int(parts[15]),
                "hmm_to": int(parts[16]),
                "hmm_len": int(parts[5]),
                "tlen": int(parts[2]),
            }
            if (not math.isfinite(hit["i_evalue"]) or hit["i_evalue"] < 0
                    or not 1 <= hit["ali_from"] <= hit["ali_to"] <= hit["tlen"]
                    or not 1 <= hit["hmm_from"] <= hit["hmm_to"] <= hit["hmm_len"]):
                raise ValueError(f"invalid domain coordinates/E-value: {path}:{line_number}")
            hits[protein].append(hit)
    return hits


def filter_overlapping(dom_hits, rule="best-evalue"):
    """Greedily retain lowest-i-Evalue hits with no shared alignment residue.

    Coordinates are one-based and inclusive. Ties use alignment start/end,
    HMM start/end/length and target length, in that order. Return coordinate
    order so tandem-domain suffixes follow sequence order, not E-value rank.
    The explicit legacy diagnostic reproduces historical start-first behavior,
    including its allowance of a shared endpoint and stable input-order ties.
    """
    if rule == "legacy-diagnostic":
        ranked = sorted(dom_hits, key=lambda h: h["ali_from"])
        selected = []
        for h in ranked:
            if not any(max(h["ali_from"], f["ali_from"]) < min(h["ali_to"], f["ali_to"])
                       for f in selected):
                selected.append(h)
        return selected
    if rule != "best-evalue":
        raise ValueError("unknown overlap rule: " + rule)
    key = lambda h: (h["i_evalue"], h["ali_from"], h["ali_to"],
                     h["hmm_from"], h["hmm_to"], h["hmm_len"], h["tlen"])
    selected = []
    for h in sorted(dom_hits, key=key):
        if not any(max(h["ali_from"], f["ali_from"]) <= min(h["ali_to"], f["ali_to"])
                   for f in selected):
            selected.append(h)
    return sorted(selected, key=lambda h: (h["ali_from"], h["ali_to"], key(h)))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--protein-dir", type=Path, default=PROTEIN_DIR,
                        help="Directory containing all three family FASTAs and hmmsearch tables")
    parser.add_argument("--output-dir", type=Path, default=Path("build/proteins"),
                        help="New output directory (default: build/proteins); never overwrites")
    parser.add_argument("--overlap-rule", choices=("best-evalue", "legacy-diagnostic"),
                        default="best-evalue", help="Best E-value with inclusive overlap; legacy is historical comparison only")
    args = parser.parse_args(argv)
    protein_dir = args.protein_dir.resolve()
    output_dir = args.output_dir.resolve()
    if (output_dir == protein_dir or protein_dir in output_dir.parents
            or output_dir in protein_dir.parents):
        parser.error("input and output directories must be separate, without nesting")
    if args.output_dir.is_symlink() or output_dir.exists():
        parser.error("output directory already exists; choose a new --output-dir")
    for family in FAMILIES:
        for suffix in (".faa", "_domtbl.txt"):
            path = protein_dir / (family + suffix)
            if not path.is_file():
                parser.error("required input is missing or not a file: " + str(path))
        # Parse every input before reserving an output directory.
        read_faa(protein_dir / (family + ".faa"))
        parse_domtbl(protein_dir / (family + "_domtbl.txt"), FAMILY_HMM[family])
    try:
        output_dir.mkdir(parents=True, exist_ok=False)
    except OSError as exc:
        parser.error("cannot create new output directory: " + str(exc))
    report_rows = []

    for family in FAMILIES:
        hmm_name = FAMILY_HMM[family]
        domtbl_path = protein_dir / (family + "_domtbl.txt")

        # Read protein sequences
        faa_path = protein_dir / (family + ".faa")
        seqs = read_faa(faa_path)

        # Parse domain hits (from hmmsearch of pcwde_3subfam.hmm against this FAA)
        dom_hits = parse_domtbl(domtbl_path, hmm_name)

        # Compute median length for fusion detection (cynipoid only, exclude outgroups)
        cynipoid_lens = [len(seq) for pid, seq in seqs.items()
                         if not any(pid.startswith(p) for p in OUTGROUP_PFX)]
        med_len = statistics.median(cynipoid_lens) if cynipoid_lens else 300

        out_path = output_dir / (family + "_trimmed.faa")
        out_f = open(out_path, "w")

        counts = {"normal": 0, "fusion": 0, "tandem": 0, "no_hit_kept": 0}

        for pid, seq in seqs.items():
            aal = len(seq)
            is_outgroup = any(pid.startswith(p) for p in OUTGROUP_PFX)

            # Get domain hits for this protein
            hits = [h for h in dom_hits.get(pid, []) if h["i_evalue"] < 1e-5]
            hits = filter_overlapping(hits, rule=args.overlap_rule)

            # Classify real vs stub domains
            real = [h for h in hits if (h["hmm_to"] - h["hmm_from"] + 1) / h["hmm_len"] > MIN_HMM_COV]
            if not real and hits:
                real = hits[:1]  # Preserve the historical earliest retained partial-hit fallback.

            if not real:
                # No domain hit — outgroups from non-CAZy sources or edge cases
                # Keep full sequence (these are typically well-curated outgroup seqs)
                out_f.write(">" + pid + "\n" + seq + "\n")
                counts["no_hit_kept"] += 1
                report_rows.append({
                    "family": family, "protein_id": pid, "aa_length": aal,
                    "classification": "no_hit_kept", "n_domains": 0,
                    "trim_coords": "full", "outgroup": is_outgroup,
                })
                continue

            n_real = len(real)

            if n_real == 1:
                # Single domain — check for fusion
                h = real[0]
                dom_len = h["ali_to"] - h["ali_from"] + 1
                if is_apparent_gene_prediction_fusion(
                    selected_target_domains=n_real,
                    protein_length=aal,
                    family_median_length=med_len,
                    aligned_target_length=dom_len,
                    is_outgroup=is_outgroup,
                ):
                    # Gene fusion — exclude
                    counts["fusion"] += 1
                    report_rows.append({
                        "family": family, "protein_id": pid, "aa_length": aal,
                        "classification": "fusion_excluded",
                        "n_domains": 1,
                        "trim_coords": str(h["ali_from"]) + "-" + str(h["ali_to"]),
                        "outgroup": is_outgroup,
                    })
                    continue

                # Normal single domain — trim to domain ± flanking
                af = h["ali_from"] - 1  # 1-based to 0-based
                at = h["ali_to"]
                trim_start = max(0, af - FLANK)
                trim_end = min(aal, at + FLANK)
                trimmed = seq[trim_start:trim_end]

                out_f.write(">" + pid + "\n" + trimmed + "\n")
                counts["normal"] += 1
                report_rows.append({
                    "family": family, "protein_id": pid, "aa_length": aal,
                    "classification": "normal",
                    "n_domains": 1,
                    "trim_coords": str(trim_start + 1) + "-" + str(trim_end),
                    "outgroup": is_outgroup,
                })

            else:
                # Multiple real domains — split into separate entries
                counts["tandem"] += 1
                for i, h in enumerate(real):
                    suffix = "_d" + str(i + 1)
                    af = h["ali_from"] - 1
                    at = h["ali_to"]
                    trim_start = max(0, af - FLANK)
                    trim_end = min(aal, at + FLANK)
                    trimmed = seq[trim_start:trim_end]

                    out_f.write(">" + pid + suffix + "\n" + trimmed + "\n")

                report_rows.append({
                    "family": family, "protein_id": pid, "aa_length": aal,
                    "classification": "tandem_split",
                    "n_domains": n_real,
                    "trim_coords": " + ".join(
                        str(h["ali_from"]) + "-" + str(h["ali_to"]) for h in real),
                    "outgroup": is_outgroup,
                })

        out_f.close()

        # Count output sequences
        out_seqs = read_faa(out_path)
        print(family + ":")
        print("  Input:    " + str(len(seqs)) + " proteins")
        print("  Output:   " + str(len(out_seqs)) + " trimmed sequences")
        print("  Normal:   " + str(counts["normal"]))
        print("  Tandem:   " + str(counts["tandem"]) + " proteins split")
        print("  Fusion:   " + str(counts["fusion"]) + " excluded")
        print("  No-hit:   " + str(counts["no_hit_kept"]) + " kept full")
        print("  Median:   " + str(int(med_len)) + " aa")
        print()

    # Write report
    report_path = output_dir / "preprocess_report.tsv"
    with open(report_path, "w") as f:
        writer = csv.DictWriter(f, delimiter="\t",
                                fieldnames=["family", "protein_id", "aa_length",
                                            "classification", "n_domains",
                                            "trim_coords", "outgroup"])
        writer.writeheader()
        for row in report_rows:
            writer.writerow(row)
    print("Report: " + str(report_path))


if __name__ == "__main__":
    main()
